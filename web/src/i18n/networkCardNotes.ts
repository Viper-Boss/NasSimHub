/**
 * The dashboard cards' short labels.
 *
 * These are badges, row names and tile captions -- ordinarily the shape of
 * string that belongs in the locale files, where short strings are cheap. They
 * are here instead because there are nearly sixty of them and NONE of them is
 * rendered anywhere but the dashboard's cards, which load lazily: in the locale
 * files they cost every visitor bytes before the app has drawn anything, and
 * the startup budget noticed immediately.
 *
 * Returned as one object so each card merges them in a single call rather than
 * once per string.
 *
 * Two prefixes carry a rule with them. `sec*` and `stats*` belong to the two
 * cards that were drawn before their backend existed, and that still meet
 * gateways older than it; `cardPending` is what those cards show in place of
 * every figure they have not been given -- so nothing in
 * either group may be worded as a state ("secure", "all clear"): the wording
 * has to survive being shown next to a row that has never been measured.
 */
export function networkCardLabels(locale: string): Record<string, string> {
  return labels[locale] ?? labels['en-US']!
}

