// Deriving a machine identity that survives reinstalling the OS.
//
// The obvious candidate, /etc/machine-id, is exactly wrong: it is regenerated
// on install, so every customer's licence would break the first time they
// reflashed. So would anything this software generates and stores itself.
// Only identifiers burned into hardware survive, and they have to be read from
// the host rather than the container -- /sys is bind-mounted into the hardware
// container for this reason.
//
// WHAT THE TARGET BOARD ACTUALLY HAS. This was written against a list of
// plausible sources and then measured on the real hardware (Rockchip RK3566,
// onethingtech OEC). The measurement removed most of the list:
//
//	/sys/firmware/devicetree/base/serial-number   absent
//	/sys/devices/soc0/serial_number               absent
//	/sys/class/dmi/id/*                           absent -- DMI is x86 firmware
//	/sys/block/mmcblk0/device/cid                 PRESENT, burned into the chip
//	end0 MAC                                      addr_assign_type=3, random
//	enx… MAC                                      the 4G MODULE's ECM interface
//	/etc/machine-id                               regenerated on reflash
//
// So on this board the eMMC CID is not a fallback, it is the only hard
// identifier there is. The ordered list below is kept because other boards do
// expose the earlier entries and there is no reason to refuse a better source
// when one exists -- but nothing here may assume more than one will be found.
//
// The measurement also found a trap, which is the reason this file was
// rewritten rather than tweaked: the module's ECM interface reports
// addr_assign_type=0, "permanent". It is permanent to the MODULE, not to the
// machine. A machine identity derived from it would be bound to whichever
// modem was plugged in, and would change when the customer swapped modules or
// simply unplugged one -- the precise failure a machine licence exists to
// avoid. MAC addresses are therefore no longer eligible to derive an identity
// at all, on any board. They are recorded, and only recorded.
//
// A second probe across a full reboot then proved that interface's
// "permanent" flag is simply false: the address changed, and because udev
// derives the interface NAME from the address, the interface came back as
// enxea2d3ee794dd where it had been enx82ae89b182c2. It advertises
// addr_assign_type=0 while being regenerated by the module's firmware on every
// boot. Excluding it stopped being a precaution and became a correction.
//
// That probe also found two sources the first one missed, both stable across
// the reboot: the Rockchip OTP (/sys/bus/nvmem/devices/rockchip-otp0/nvmem)
// and the kernel's own Serial line in /proc/cpuinfo. Both live in the SoC, so
// they survive replacing the storage -- which is what finally makes a repaired
// board distinguishable from a stranger's. See cpuSerial and otpRegion below
// for which one is trusted with that job, and why it is not the OTP.

// identitySalt keeps the machine ID from being computable by anyone holding the
// device. It buys little on its own -- the ID is not a secret and forging a
// certificate needs the issuer's private key regardless -- but there is no
// reason to publish the derivation either.
//
// Changing this value invalidates every machine certificate ever issued.
const identitySalt = "nassimhub/machine-id/v1"

// DerivationVersion is bumped when the rules below change in a way that would
// produce a different ID for the same machine. A stored fingerprint carrying an
// older version is a re-issue case, not a mismatch, and saying so is the
// difference between a support answer and a mystery.
const DerivationVersion = 2

// hardwareSource is one identifier and where it comes from.
type hardwareSource struct {
	// Name is stable and appears in the stored fingerprint.
	Name string
	// Path is read directly; sysfs values are trimmed of NUL and whitespace.
	Path string
	// Derives marks sources an identity may be computed from. A source that is
	// recorded but does not derive is diagnostic only.
	Derives bool
	// Identifying marks sources that name ONE unit rather than a model or an
	// installation. Only these may corroborate that two fingerprints came from
	// the same physical machine. A model string is shared by every board of
	// that model, so treating it as corroboration would let any customer with
	// the same hardware claim to be any other.
	Identifying bool
}

// fixedSources are the single-path identifiers, in the order they are
// preferred. Everything here is burned into the SoC or its firmware.
//
// The eMMC CID is not in this list because its path depends on which block
// device enumerated; it is collected separately and ranks immediately after
// these.
var fixedSources = []hardwareSource{
	// Read from the SoC's own eFuse on boards whose vendor sets it. Absent on
	// the measured board, present on plenty of others.
	{Name: "dt-serial", Path: "/sys/firmware/devicetree/base/serial-number", Derives: true, Identifying: true},
	{Name: "soc-serial", Path: "/sys/devices/soc0/serial_number", Derives: true, Identifying: true},
	// x86 firmware identifiers. Absent on ARM, which is most of the fleet, but
	// this software also runs on x86 NAS boxes where they are the best source.
	{Name: "dmi-uuid", Path: "/sys/class/dmi/id/product_uuid", Derives: true, Identifying: true},
	{Name: "dmi-board", Path: "/sys/class/dmi/id/board_serial", Derives: true, Identifying: true},
	// Recorded, and neither derives nor corroborates. The board model is shared
	// by every unit of that model, so it can never be evidence that two
	// fingerprints came from the same board -- but knowing it turns "the ID
	// changed" into "the ID changed on an RK3566, where the CID is expected to
	// be the source", which is the first thing a support reply needs.
	{Name: "dt-compatible", Path: "/sys/firmware/devicetree/base/compatible"},
	// Regenerated on reinstall, so it can neither derive nor corroborate. It is
	// recorded because a changed machine-id beside an UNCHANGED identity is
	// positive evidence the customer reflashed and nothing else happened.
	{Name: "os-machine-id", Path: "/etc/machine-id"},
}

// Fingerprint is every identifier seen, with the one the ID came from named.
type Fingerprint struct {
	// MachineID is the derived identity.
	MachineID string `json:"machine_id"`
	// PrimarySource is which source produced it.
	PrimarySource string `json:"primary_source"`
	// Sources maps source name to the value seen. Values are stored raw so a
	// later mismatch can be shown to a human, who is the only one able to say
	// whether a board was replaced.
	Sources map[string]string `json:"sources"`
	// Version guards against a future change to the derivation silently
	// producing a different ID for the same machine.
	Version int `json:"version"`
}

// readSource reads one sysfs value, or "" when absent.
func readSource(root, path string) string {
	raw, err := os.ReadFile(filepath.Join(root, strings.TrimPrefix(path, "/")))
	if err != nil {
		return ""
	}
	// Device-tree strings are NUL-terminated, and some (compatible) are a list
	// of NUL-separated strings; sysfs values carry a newline.
	value := strings.TrimSpace(strings.ReplaceAll(strings.TrimRight(string(raw), "\x00\n"), "\x00", " "))
	// A few boards report a placeholder where the vendor left the field unset.
	// Treating those as an identity would give every such board the same one.
	switch strings.ToLower(value) {
	case "", "0", "00000000", "unknown", "none", "default string",
		"to be filled by o.e.m.", "ffffffffffffffff", "0x0000000000000000":
		return ""
	}
	return value
}

// moduleInterfacePrefixes are interfaces whose MAC belongs to something other
// than this machine.
//
// "enx" is the predictable name udev gives a USB network interface, derived
// from the MAC itself -- which is how the 4G module's ECM interface appears.
// The rest are virtual interfaces this software or its containers create.
var moduleInterfacePrefixes = []string{
	"enx", "usb", "wwan", "rndis", // the modem, under its various driver names
	"veth", "docker", "br-", "wg", "tun", "tap", "virbr", // ours, not hardware
}

// macSources collects MAC addresses for the record.
//
// These NEVER derive an identity. addr_assign_type=0 means the address is
// permanent to the INTERFACE, which is not the same as permanent to the
// machine: on the measured board the only interface reporting permanent is the
// 4G module's, and binding a machine licence to a removable modem is the exact
// mistake this function used to make.
func macSources(root string) map[string]string {
	found := map[string]string{}
	base := filepath.Join(root, "sys/class/net")
	entries, err := os.ReadDir(base)
	if err != nil {
		return found
	}
	for _, entry := range entries {
		name := entry.Name()
		if name == "lo" {
			continue
		}
		if isModuleOrVirtualInterface(name) {
			continue
		}
		address := readSource(root, "/sys/class/net/"+name+"/address")
		if address == "" || address == "00:00:00:00:00:00" {
			continue
		}
		// A randomised address changes every boot and would make the record
		// noisy without adding anything, so it is labelled rather than dropped:
		// seeing "this board's only NIC is random" in a support file explains
		// why the fingerprint is thin.
		if assign := readSource(root, "/sys/class/net/"+name+"/addr_assign_type"); assign != "0" {
			found["mac-"+name+"-random"] = address
			continue
		}
		found["mac-"+name] = address
	}
	return found
}

func isModuleOrVirtualInterface(name string) bool {
	for _, prefix := range moduleInterfacePrefixes {
		if strings.HasPrefix(name, prefix) {
			return true
		}
	}
	return false
}

// cpuSerial reads the kernel's Serial line out of /proc/cpuinfo.
//
// THIS is the second identifying source, not the OTP, and the choice matters
// enough to justify the length of this comment.
//
// The OTP region on the measured board reads:
//
//	+00  52 4b 35 66 02 00 fe 21   |RK5f...!|
//	+08  10 01 54 4b 57 4c 31 39   |..TKWL19|
//	+16  00 00 00 00 00 00 00 0d   |........|
//	+24  13 0a 1b 38 04 08 00      |...8...|
//
// "RK5f" is a family magic and "TKWL19" is an ASCII code that reads like a
// wafer or batch marking; the rest is mostly zeros and a short run that could
// be a date. There is exactly ONE board to compare, so which of those bytes
// vary per unit is unknown. Hashing the region and calling the result an
// identity would risk hashing a batch code -- and a batch code corroborating
// "same machine" is the same bug as a model string corroborating it, which a
// test in this package already caught once, only harder to see because the
// value looks random.
//
// /proc/cpuinfo's Serial, by contrast, is a single value the kernel itself
// presents as a serial number, it is stable across a reboot (measured), and it
// does not appear anywhere in the OTP window above -- so it is not a slice of
// the batch marking. It is the better candidate on the evidence available.
//
// Honest about the limit: per-unit uniqueness is inferred from one board, not
// measured across two. The consequence if that inference is wrong is bounded
// and worth stating -- a stranger's board would corroborate and report
// "storage-replaced" instead of "undetermined". Both route to a person who
// checks the purchase record; neither grants anything. Nothing here derives an
// identity from this value, so a collision cannot hand one machine another's
// licence.
func cpuSerial(root string) string {
	raw, err := os.ReadFile(filepath.Join(root, "proc/cpuinfo"))
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(raw), "\n") {
		name, value, found := strings.Cut(line, ":")
		if !found || !strings.EqualFold(strings.TrimSpace(name), "serial") {
			continue
		}
		value = strings.TrimSpace(value)
		// x86 kernels omit this line; ARM kernels that have nothing to report
		// print a run of zeros, which is not an identity.
		if value == "" || strings.Trim(value, "0") == "" {
			return ""
		}
		return strings.ToLower(value)
	}
	return ""
}

// otpPaths are where the Rockchip one-time-programmable area surfaces. Which
// one exists depends on the kernel's nvmem bindings, so all of them are tried.
var otpPaths = []string{
	"/sys/bus/nvmem/devices/rockchip-otp0/nvmem",
	"/sys/bus/nvmem/devices/rockchip-efuse0/nvmem",
}

// otpRegion records the OTP bytes for diagnosis. It is NOT an identity and NOT
// corroboration -- see cpuSerial for why. It is here because a support case
// starting "the licence stopped matching" is far easier to answer holding the
// chip's own factory bytes than not, and because the day a second board exists
// this recorded value is what makes the per-unit question answerable.
func otpRegion(root string) string {
	for _, path := range otpPaths {
		raw, err := os.ReadFile(filepath.Join(root, strings.TrimPrefix(path, "/")))
		if err != nil || len(raw) == 0 {
			continue
		}
		if len(raw) > 32 {
			raw = raw[:32]
		}
		// All-zero means the driver exposed the region but it was never
		// programmed, which is no more an identifier than an absent file.
		empty := true
		for _, value := range raw {
			if value != 0 {
				empty = false
				break
			}
		}
		if empty {
			continue
		}
		return hex.EncodeToString(raw)
	}
	return ""
}

// emmcSources collects storage chip identifiers.
//
// The CID is assigned by the chip manufacturer and lives in the chip's own
// register set, not in its contents, so it survives reflashing, repartitioning
// and a full reinstall. It does not survive replacing the chip -- see
// CompareFingerprint, which exists to make that case legible.
func emmcSources(root string) map[string]string {
	found := map[string]string{}
	entries, err := os.ReadDir(filepath.Join(root, "sys/block"))
	if err != nil {
		return found
	}
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasPrefix(name, "mmcblk") {
			continue
		}
		// boot and rpmb partitions appear as separate blocks with the same
		// CID; counting them would add duplicates, not information.
		if strings.Contains(name, "boot") || strings.Contains(name, "rpmb") {
			continue
		}
		if cid := readSource(root, "/sys/block/"+name+"/device/cid"); cid != "" {
			found["emmc-cid-"+name] = cid
		}
	}
	return found
}

// CollectFingerprint reads every available identifier.
//
// root is "" in production and a fixture directory in tests, which is what
// makes this testable at all: the alternative is a function that can only be
// checked on the hardware it was written for.
func CollectFingerprint(root string) (Fingerprint, error) {
	sources := map[string]string{}
	for _, source := range fixedSources {
		if value := readSource(root, source.Path); value != "" {
			sources[source.Name] = value
		}
	}
	for name, value := range emmcSources(root) {
		sources[name] = value
	}
	// Lives in the SoC, so it survives replacing the storage. This is the
	// source that lets a repaired board be told from a stranger's.
	if serial := cpuSerial(root); serial != "" {
		sources["cpu-serial"] = serial
	}
	// Recorded for diagnosis only; never an identity, never corroboration.
	if otp := otpRegion(root); otp != "" {
		sources["otp-region"] = otp
	}
	for name, value := range macSources(root) {
		sources[name] = value
	}

	primaryName, primaryValue := choosePrimary(sources)
	if primaryName == "" {
		// Refusing is correct. Inventing an identity here -- a random value
		// written to disk, say -- would produce a licence that silently died
		// on the next reflash, which is the exact failure this package exists
		// to avoid.
		return Fingerprint{}, fmt.Errorf(
			"license: no hardware identifier this machine cannot change; a machine licence cannot be bound",
		)
	}

	digest := sha256.Sum256([]byte(identitySalt + "\x00" + primaryName + "\x00" + primaryValue))
	return Fingerprint{
		MachineID:     hex.EncodeToString(digest[:8]),
		PrimarySource: primaryName,
		Sources:       sources,
		Version:       DerivationVersion,
	}, nil
}

// choosePrimary picks the best available source in the fixed order.
//
// MACs are absent from this function on purpose and there is no final fallback
// to them: a board with no burned-in identifier gets no machine licence, and
// is told so, rather than getting one bound to a removable part.
func choosePrimary(sources map[string]string) (string, string) {
	for _, source := range fixedSources {
		if !source.Derives {
			continue
		}
		if value, ok := sources[source.Name]; ok {
			return source.Name, value
		}
	}
	// The storage chip, by name so the choice does not depend on map order.
	// On every ARM board measured so far this is the branch that runs.
	var emmc []string
	for name := range sources {
		if strings.HasPrefix(name, "emmc-cid-") {
			emmc = append(emmc, name)
		}
	}
	if len(emmc) > 0 {
		sort.Strings(emmc)
		return emmc[0], sources[emmc[0]]
	}
	// cpu-serial stops here deliberately and is not a further fallback.
	//
	// It is trusted to CORROBORATE an identity but not to BE one, and the
	// asymmetry is the point. A wrong guess about corroboration mislabels a
	// support case, which a person then sorts out. A wrong guess about
	// derivation means two boards sharing a batch value share a machine ID,
	// and one customer's certificate silently unlocks another's gateway. The
	// first is recoverable and the second is not, so a board with no burned-in
	// unit identifier is refused a machine licence and told why.
	return "", ""
}

// Verdict is what a comparison concluded, for a human to act on.
type Verdict string

const (
	// VerdictSame is the ordinary case: same machine, licence still applies.
	VerdictSame Verdict = "same"
	// VerdictReinstalled means the identity holds and softer identifiers moved
	// -- a reflash or an OS upgrade. Nothing to do.
	VerdictReinstalled Verdict = "reinstalled"
	// VerdictStorageReplaced means the identity came from an eMMC CID that
	// changed, while a source that names THIS unit still agrees. Only boards
	// carrying a second identifying source can ever reach this verdict.
	VerdictStorageReplaced Verdict = "storage-replaced"
	// VerdictUndetermined means the identity changed and this software cannot
	// tell why.
	//
	// On the shipping board this is the ONLY thing it can honestly say about a
	// changed identity, and pretending otherwise was the bug this verdict
	// replaced. That board has exactly one identifying source, the eMMC CID.
	// Replace the chip and it is gone; the model string is shared with every
	// other unit, /etc/machine-id is regenerated by the reinstall a chip swap
	// forces, and the only on-board NIC randomises its MAC every boot. A
	// repaired board and a stranger's board of the same model therefore produce
	// fingerprints that are genuinely indistinguishable. Whether a customer
	// repaired their machine is a question about purchase records and serial
	// numbers, which live outside this software; it must be answered there
	// rather than guessed at here.
	VerdictUndetermined Verdict = "undetermined"
	// VerdictDifferentMachine means the identity changed and an identifying
	// source positively disagrees -- not merely absent, but present and
	// different.
	VerdictDifferentMachine Verdict = "different-machine"
	// VerdictDerivationChanged means this build computes IDs differently from
	// the build that stored the fingerprint. Not the customer's doing.
	VerdictDerivationChanged Verdict = "derivation-changed"
)

// Drift describes how a freshly read fingerprint compares to the stored one.
type Drift struct {
	// SameID is true when the derived machine ID is unchanged. It is the ONLY
	// field anything is allowed to grant a licence on.
	SameID bool
	// Verdict explains a changed ID in terms a person can act on.
	Verdict Verdict
	// Matching and Changed count the sources present in both that agree and
	// disagree. Diagnostic only.
	Matching int
	Changed  int
	// Corroborating names the sources that still agree, so a support reply can
	// quote them instead of asserting a conclusion.
	Corroborating []string
}

// CompareFingerprint explains a changed machine ID.
//
// It decides NOTHING. An earlier version of this returned
// "LooksLikeSameMachine" when a couple of identifiers still agreed, on the
// theory that a machine with several hardware sources could lose one and be
// recognised by the rest. The hardware measurement killed that theory: the
// target board has exactly one identifier that derives an ID, so "most of the
// others still agree" can be true while the one that matters has changed, and
// a caller that trusted the flag would hand out a licence on the strength of a
// randomised MAC and a model string. The flag is gone. What remains is an
// explanation for a person, and SameID for the machine.
func CompareFingerprint(stored, current Fingerprint) Drift {
	drift := Drift{SameID: stored.MachineID == current.MachineID}
	identifyingAgrees := 0
	identifyingDisagrees := 0

	for name, value := range stored.Sources {
		other, present := current.Sources[name]
		if !present {
			continue
		}
		// A randomised MAC differs on every boot by design; counting it as
		// evidence either way would be counting noise. On the shipping board
		// it is the only on-board NIC, so counting it would poison every
		// comparison that board ever makes.
		if strings.HasSuffix(name, "-random") {
			continue
		}
		// The source that derived the stored identity is excluded from the
		// verdict. Its change is the PREMISE -- it is why we are explaining
		// anything at all -- not evidence about the cause. Counting it would
		// make every changed identity self-certify as a different machine and
		// no repair could ever be recognised.
		evidence := name != stored.PrimarySource

		if other == value {
			drift.Matching++
			drift.Corroborating = append(drift.Corroborating, name)
			if evidence && identifies(name) {
				identifyingAgrees++
			}
		} else {
			drift.Changed++
			if evidence && identifies(name) {
				identifyingDisagrees++
			}
		}
	}
	sort.Strings(drift.Corroborating)

	switch {
	case drift.SameID:
		drift.Verdict = VerdictSame
		if drift.Changed > 0 {
			drift.Verdict = VerdictReinstalled
		}
	case stored.Version != current.Version:
		drift.Verdict = VerdictDerivationChanged
	case identifyingDisagrees > 0:
		// Something that names a particular unit is present and says a
		// different unit. That is the one case this software can call.
		drift.Verdict = VerdictDifferentMachine
	case strings.HasPrefix(stored.PrimarySource, "emmc-cid-") && identifyingAgrees > 0:
		drift.Verdict = VerdictStorageReplaced
	default:
		drift.Verdict = VerdictUndetermined
	}
	return drift
}

// identifies reports whether a source names one unit rather than a model, a
// batch or an installation.
func identifies(name string) bool {
	for _, source := range fixedSources {
		if source.Name == name {
			return source.Identifying
		}
	}
	switch {
	case name == "cpu-serial":
		// The SoC's own serial. Survives replacing the storage, which is the
		// whole reason a repair can now be told from a stranger.
		return true
	case name == "otp-region":
		// Deliberately not. The readable window is a family magic plus what
		// looks like a batch marking, and with one board in hand there is no
		// way to know which bytes vary per unit. See otpRegion.
		return false
	case strings.HasPrefix(name, "mac-"):
		// A permanent MAC on a board that has a real one names that board. A
		// randomised one is skipped before reaching here, and the module's
		// interfaces never enter the fingerprint at all.
		return true
	case strings.HasPrefix(name, "emmc-cid-"):
		return true
	default:
		return false
	}
}

// NeedsHumanDecision reports whether a changed identity is worth routing to a
// person rather than refusing outright.
//
// It is deliberately NOT called something like "Rebindable", because it does
// not mean the machine may be rebound. VerdictUndetermined is included: on the
// shipping board a genuine repair lands there, and so does a stranger, and the
// software cannot separate them. Refusing both would strand every customer who
// ever has a board repaired; granting both would hand a licence to anyone who
// asks. Neither is this code's call. It routes the case to whoever holds the
// purchase records and stops.
func (d Drift) NeedsHumanDecision() bool {
	switch d.Verdict {
	case VerdictStorageReplaced, VerdictDerivationChanged, VerdictUndetermined:
		return true
	default:
		return false
	}
}
