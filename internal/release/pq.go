// Dual-signed release manifests.
//
// A dual-signed manifest carries two signatures over the same manifest: the
// Ed25519 one every gateway has always checked, and an ML-DSA one. BOTH must
// verify. Either algorithm failing alone then does not let a forged release
// through: a broken Ed25519 is caught by ML-DSA, and a flaw found in the much
// younger ML-DSA is caught by Ed25519.
//
// It is a separate document type at a separate published path, for the reason
// DefaultSignedManifestURLTemplate records: gateways in the field decode the
// classical envelope with unknown fields disallowed, so adding a field to it
// would make every one of them refuse every future release. They keep reading
// the classical document; a build with a post-quantum key reads this one.
//
// WHICH ONE A BUILD ACCEPTS IS DECIDED AT BUILD TIME AND NEVER AT RUN TIME.
// A build with PQSigningPublicKey set accepts only dual-signed manifests, from
// every source. There is no "prefer dual, fall back to classical": a fallback
// an attacker can trigger by withholding one document is not a requirement.
// A build without the key accepts classical manifests and says, wherever it
// reports its update signature, that it is not post-quantum.

// PQSigningAlgorithm is the post-quantum algorithm releases are signed with.
const PQSigningAlgorithm = pqsig.MLDSA87

// PQSigningPublicKey is the base64 ML-DSA-87 public key dual-signed release
// manifests are verified against.
//
// EMPTY IN THIS TREE, DELIBERATELY. The key pair is generated by the release
// process (licensegen release-pq-keygen), on the issuer's machine, and only
// its public half is ever pasted here. Until that is done this build verifies
// classical manifests only - and reports exactly that.
const PQSigningPublicKey = ""

// PQDomain separates the post-quantum signature from every other use of the
// key, the way Domain does for Ed25519. It is prepended to the same canonical
// bytes the Ed25519 signature covers, so the two signatures can never attest
// to two different manifests.
const PQDomain = "nsh-domain=release-manifest-pq-v1"

// SignaturePolicy says what a build demands of a release manifest.
type SignaturePolicy string

const (
	// PolicyClassical: Ed25519 only; this build has no post-quantum key.
	PolicyClassical SignaturePolicy = "classical"
	// PolicyDualRequired: Ed25519 and ML-DSA, both required.
	PolicyDualRequired SignaturePolicy = "dual_required"
)

// PQSignaturePolicy reports this build's policy.
func PQSignaturePolicy() SignaturePolicy { return policyFor(PQSigningPublicKey) }

func policyFor(pqKey string) SignaturePolicy {
	if strings.TrimSpace(pqKey) == "" {
		return PolicyClassical
	}
	return PolicyDualRequired
}

// ErrPQUnavailable means this build cannot check an ML-DSA signature at all
// (it was built with a toolchain older than the one that has crypto/mldsa).
// It is never a reason to accept the manifest.
var ErrPQUnavailable = errors.New("release: this build cannot verify a post-quantum signature")

// SignedDual is a manifest with both signatures.
type SignedDual struct {
	Manifest    Manifest `json:"manifest"`
	Signature   string   `json:"signature"`
	PQAlgorithm string   `json:"pq_algorithm"`
	PQSignature string   `json:"pq_signature"`
}

func pqMessage(canonical []byte) []byte {
	return append([]byte(PQDomain+"\n"), canonical...)
}

// VerifyDual checks both signatures and returns the manifest only when both
// verify. The Ed25519 check is Verify itself, so the classical half can never
// drift from what classical gateways accept.
func VerifyDual(signed SignedDual, publicKeyBase64, pqPublicKeyBase64 string) (Manifest, error) {
	manifest, err := Verify(Signed{Manifest: signed.Manifest, Signature: signed.Signature}, publicKeyBase64)
	if err != nil {
		return Manifest{}, err
	}
	if signed.PQAlgorithm != PQSigningAlgorithm {
		return Manifest{}, fmt.Errorf("%w: post-quantum algorithm is %q, this build accepts %s",
			ErrBadSignature, signed.PQAlgorithm, PQSigningAlgorithm)
	}
	key, err := base64.StdEncoding.DecodeString(strings.TrimSpace(pqPublicKeyBase64))
	if err != nil || len(key) == 0 {
		return Manifest{}, fmt.Errorf("%w: post-quantum verification key is not readable", ErrMalformed)
	}
	signature, err := base64.StdEncoding.DecodeString(strings.TrimSpace(signed.PQSignature))
	if err != nil || len(signature) == 0 {
		return Manifest{}, fmt.Errorf("%w: post-quantum signature is missing or not base64", ErrBadSignature)
	}
	canonical, err := manifest.canonical()
	if err != nil {
		return Manifest{}, err
	}
	// Without an implementation there is no verifier, and the manifest is
	// refused - never waved through.
	if err := pqsig.Verify(signed.PQAlgorithm, key, pqMessage(canonical), signature); err != nil {
		if errors.Is(err, pqsig.ErrUnavailable) {
			return Manifest{}, fmt.Errorf("%w: %v", ErrPQUnavailable, err)
		}
		return Manifest{}, fmt.Errorf("%w: post-quantum signature does not verify", ErrBadSignature)
	}
	return manifest, nil
}

// VerifyDualJSON reads and verifies a dual-signed envelope, bounded and with
// unknown fields refused, like VerifyJSON.
func VerifyDualJSON(reader io.Reader, publicKeyBase64, pqPublicKeyBase64 string) (Manifest, error) {
	var signed SignedDual
	decoder := json.NewDecoder(io.LimitReader(reader, maxDualManifestBytes))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&signed); err != nil {
		return Manifest{}, fmt.Errorf("%w: %v", ErrMalformed, err)
	}
	return VerifyDual(signed, publicKeyBase64, pqPublicKeyBase64)
}

// maxDualManifestBytes allows for an ML-DSA-87 signature (4627 bytes, about
// 6.2 kB in base64) on top of a classical manifest.
const maxDualManifestBytes = maxManifestBytes + 16<<10

// MaxDualManifestBytes is the transport ceiling for a dual-signed manifest.
const MaxDualManifestBytes = maxDualManifestBytes

// SignDual produces a dual-signed envelope and verifies it before returning
// it. A post-quantum signer that fails is an error, not a classical manifest:
// a publisher who believes they dual-signed and did not would ship a release
// that every dual-required gateway refuses.
func SignDual(manifest Manifest, privateKey ed25519.PrivateKey, pq pqsig.Signer) (SignedDual, error) {
	if pq == nil {
		return SignedDual{}, fmt.Errorf("%w: a post-quantum signer is required", ErrMalformed)
	}
	if pq.Algorithm() != PQSigningAlgorithm {
		return SignedDual{}, fmt.Errorf("%w: releases are signed with %s, not %s", ErrMalformed, PQSigningAlgorithm, pq.Algorithm())
	}
	classical, err := Sign(manifest, privateKey)
	if err != nil {
		return SignedDual{}, err
	}
	canonical, err := manifest.canonical()
	if err != nil {
		return SignedDual{}, err
	}
	signature, err := pq.Sign(pqMessage(canonical))
	if err != nil {
		return SignedDual{}, fmt.Errorf("release: post-quantum signing failed: %w", err)
	}
	signed := SignedDual{Manifest: manifest, Signature: classical.Signature, PQAlgorithm: PQSigningAlgorithm,
		PQSignature: base64.StdEncoding.EncodeToString(signature)}
	public := privateKey.Public().(ed25519.PublicKey)
	if _, err := VerifyDual(signed, base64.StdEncoding.EncodeToString(public), base64.StdEncoding.EncodeToString(pq.PublicKey())); err != nil {
		return SignedDual{}, fmt.Errorf("release: refusing to emit a manifest that does not verify: %w", err)
	}
	return signed, nil
}

// VerifyPublished verifies a published manifest the way THIS BUILD requires:
// dual-signed when it has a post-quantum key, classical when it does not.
// Every channel a manifest can arrive by - the release URL, a peer, a file -
// goes through here, so no channel can be the weak one.
func VerifyPublished(document []byte, publicKeyBase64 string) (Manifest, error) {
	return verifyPublished(document, publicKeyBase64, PQSigningPublicKey)
}

// MaxPublishedBytes is the largest manifest document this build reads from any
// channel: the dual-signed ceiling when it requires dual signatures, the
// classical one otherwise.
func MaxPublishedBytes() int {
	if PQSignaturePolicy() == PolicyDualRequired {
		return maxDualManifestBytes
	}
	return maxManifestBytes
}

// PublishedManifestName is the file a release publishes its manifest as, for
// this build's policy. Two names, so that classical gateways in the field keep
// finding the document they can read.
func PublishedManifestName() string {
	if PQSignaturePolicy() == PolicyDualRequired {
		return "release.signed.pq.json"
	}
	return "release.signed.json"
}

func verifyPublished(document []byte, publicKeyBase64, pqPublicKeyBase64 string) (Manifest, error) {
	if policyFor(pqPublicKeyBase64) == PolicyDualRequired {
		return VerifyDualJSON(bytes.NewReader(document), publicKeyBase64, pqPublicKeyBase64)
	}
	return VerifyJSON(bytes.NewReader(document), publicKeyBase64)
}
